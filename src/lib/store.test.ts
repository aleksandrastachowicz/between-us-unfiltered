import { it, expect, vi } from "vitest";
vi.mock("@/lib/unfilteredClient", () => { let n = 0; return { primeUnfiltered: () => {}, nextUnfiltered: () => ({ id: "u" + n++, pl: "a", en: "b", level: "love_spice", intensity: 1 }) }; });
vi.stubGlobal("localStorage", { getItem: () => null, setItem: () => {}, removeItem: () => {} });
import { useGame } from "@/lib/store";
it("offers a level up every 8 cards and moves level", () => {
  useGame.setState({ decks: { basic: true, plus: false, unfiltered: true } as any });
  useGame.getState().startGame();
  for (let i = 0; i < 6; i++) useGame.getState().drawCard();
  expect(useGame.getState().levelUpOpen).toBe(false);
  useGame.getState().drawCard();
  expect(useGame.getState().levelUpOpen).toBe(true);
  useGame.getState().acceptLevelUp();
  expect(useGame.getState().ufLevel).toBe("after_dark");
  expect(useGame.getState().progress).toBe(50);
  for (let i = 0; i < 8; i++) useGame.getState().drawCard();
  expect(useGame.getState().levelUpOpen).toBe(true);
  useGame.getState().declineLevelUp();
  expect(useGame.getState().ufLevel).toBe("after_dark");
  useGame.getState().setUfLevel("love_spice");
  expect(useGame.getState().progress).toBe(15);
});
